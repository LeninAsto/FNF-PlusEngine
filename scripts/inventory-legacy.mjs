import { readdir, readFile, writeFile } from 'node:fs/promises';
import { relative, resolve, sep } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const legacyRoot = resolve(root, 'docs');

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(path));
    else files.push(path);
  }
  return files;
}

function webPath(file) {
  const path = `/${relative(legacyRoot, file).split(sep).join('/')}`;
  return path.endsWith('/index.html') ? path.slice(0, -'index.html'.length) : path;
}

function targetFor(source) {
  if (source === '/') return '/';
  if (source === '/es/') return '/es-LA/';
  if (source === '/psych/') return '/api/psych/';
  if (source === '/es/psych/') return '/es-LA/api/psych/';
  if (source === '/plus/') return '/api/plus/';
  if (source === '/es/plus/') return '/es-LA/api/plus/';

  let match = source.match(/^\/pages\/([^/]+)\/$/);
  if (match) return `/api/psych/${match[1]}/`;
  match = source.match(/^\/es\/pages\/([^/]+)\/$/);
  if (match) return `/es-LA/api/psych/${match[1]}/`;
  match = source.match(/^\/plus\/pages\/([^/]+)\/$/);
  if (match) return `/api/plus/${match[1]}/`;
  match = source.match(/^\/es\/plus\/pages\/([^/]+)\/$/);
  if (match) return `/es-LA/api/plus/${match[1]}/`;
  return null;
}

function contentPaths(target) {
  const route = target.replace(/^\//, '').replace(/\/$/, '');
  const base = resolve(root, 'src/content/docs');
  if (!route) return [resolve(base, 'index.mdx')];
  return [resolve(base, `${route}.mdx`), resolve(base, route, 'index.mdx')];
}

const files = await walk(legacyRoot);
const htmlFiles = files.filter((file) => file.endsWith('.html'));
const routes = await Promise.all(htmlFiles.map(async (file) => {
  const html = await readFile(file, 'utf8');
  const source = webPath(file);
  const target = targetFor(source);
  const anchors = [...html.matchAll(/\sid=["']([^"']+)["']/g)].map((match) => match[1]);
  let implemented = false;
  if (target) {
    for (const candidate of contentPaths(target)) {
      try {
        await readFile(candidate);
        implemented = true;
        break;
      } catch {}
    }
  }
  return { source, target, implemented, anchors };
}));

routes.sort((a, b) => a.source.localeCompare(b.source));
const assetFiles = files.filter((file) => !file.endsWith('.html'));
const videoFiles = assetFiles.filter((file) => /\.(mp4|webm)$/i.test(file));
const dataFiles = assetFiles.filter((file) => file.endsWith('.json'));
const videoMigrations = await Promise.all(videoFiles.map(async (file) => {
  const source = `/${relative(legacyRoot, file).split(sep).join('/')}`;
  const target = `/videos/${file.split(sep).at(-1)}`;
  try {
    await readFile(resolve(root, 'public', target.slice(1)));
    return { source, target, implemented: true };
  } catch {
    return { source, target, implemented: false };
  }
}));

const lines = [
  '# Legacy documentation migration map',
  '',
  '> Generated by `npm run inventory`. Do not edit this file by hand.',
  '',
  `Legacy HTML routes: **${routes.length}**  `,
  `Data files: **${dataFiles.length}**  `,
  `Local videos: **${videoFiles.length}**`,
  '',
  '| Legacy route | V2 route | Status | Static anchors |',
  '|---|---|---|---|',
  ...routes.map(({ source, target, implemented, anchors }) => {
    const status = target ? (implemented ? 'Implemented' : 'Pending content') : 'Needs decision';
    const anchorList = anchors.length ? anchors.map((anchor) => `\`${anchor}\``).join(', ') : 'Generated at runtime / none';
    return `| \`${source}\` | ${target ? `\`${target}\`` : '—'} | ${status} | ${anchorList} |`;
  }),
  '',
  '## Video asset migration',
  '',
  '| Legacy asset | V2 asset | Status |',
  '|---|---|---|',
  ...videoMigrations.map(({ source, target, implemented }) =>
    `| \`${source}\` | \`${target}\` | ${implemented ? 'Implemented' : 'Pending content'} |`
  ),
  '',
  'Redirects are added to `public/_redirects` only after their destination exists. This prevents replacing a working legacy URL with a v2 404.',
  ''
];

await writeFile(resolve(root, 'MIGRATION_MAP.md'), lines.join('\n'));

const redirects = ['# Generated by npm run inventory. Add redirects only after their destination exists.'];
for (const { source, target, implemented } of routes) {
  if (!implemented || !target || source === target) continue;
  const withoutSlash = source === '/' ? '/' : source.replace(/\/$/, '');
  redirects.push(`${withoutSlash} ${target} 301`);
  if (source !== withoutSlash) redirects.push(`${source} ${target} 301`);
  if (source.endsWith('/')) redirects.push(`${source}index.html ${target} 301`);
}
await writeFile(resolve(root, 'public/_redirects'), `${redirects.join('\n')}\n`);

console.log(`Inventoried ${routes.length} HTML routes, ${dataFiles.length} data files, ${videoFiles.length} videos, and ${redirects.length - 1} redirects.`);
